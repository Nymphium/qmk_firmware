layer_state_t layer_state_set_user(layer_state_t state) {
    state = update_tri_layer_state(state, _LOWER, _SHIFT, _LSHIFT);
    state = update_tri_layer_state(state, _NUM, _LOWER, _NMODS);
    return state;
}

bool process_record_user(uint16_t keycode, keyrecord_t *record) {
    switch (keycode) {
        case JP_COLN:
            if (record->event.pressed) {
                unregister_code(KC_LSFT);
            } else {
                if (get_mods() & MOD_MASK_SHIFT) register_code(KC_LSFT);
                unregister_code(keycode);
            }
            return true;

        case KC_LSFT:
            if (record->event.pressed) {
                register_code(keycode);

                if (!(get_mods() & (MOD_MASK_CTRL | MOD_MASK_ALT | MOD_MASK_GUI))) {
                    layer_on(_SHIFT);
                }
            } else {
                layer_off(_SHIFT);
                unregister_code(keycode);
            }
            return false;
    }

    return true;
}
