static bool shift = false;
static bool modkeyed = false;

bool process_record_user(uint16_t keycode, keyrecord_t *record) {
    switch (keycode) {
        case KC_LGUI:
        case KC_LALT:
        case KC_LCTL:
            if (record->event.pressed) {
                register_code(keycode);
                modkeyed = true;
            } else {
                unregister_code(keycode);
                modkeyed = false;
            }
            return false;

        case JP_COLN:
            if (record->event.pressed) {
                unregister_code(KC_LSFT);
            } else {
                if (shift) register_code(KC_LSFT);
                unregister_code(keycode);
            }
            return true;

        case KC_LSFT:
            if (record->event.pressed) {
                register_code(keycode);

                if (!modkeyed) {
                    shift = true;
                    layer_on(_SHIFT);
                    update_tri_layer(_LOWER, _SHIFT, _LSHIFT);
                }
            } else {
                if (shift) {
                    shift = false;
                    layer_off(_SHIFT);
                    update_tri_layer(_LOWER, _SHIFT, _LSHIFT);
                }
                unregister_code(keycode);
            }
            return false;

        case LOWER:
            if (record->event.pressed) {
                layer_on(_LOWER);
                update_tri_layer(_LOWER, _SHIFT, _LSHIFT);
                update_tri_layer(_NUM, _LOWER, _NMODS);
            } else {
                layer_off(_LOWER);
                update_tri_layer(_LOWER, _SHIFT, _LSHIFT);
                update_tri_layer(_NUM, _LOWER, _NMODS);
            }
            return false;

        case NUM:
            if (record->event.pressed) {
                layer_on(_NUM);
                update_tri_layer(_NUM, _LOWER, _NMODS);
            } else {
                layer_off(_NUM);
                update_tri_layer(_NUM, _LOWER, _NMODS);
            }
            return false;

        case S(BOOTLDR):
            if (record->event.pressed) {
                eeconfig_init();
                reset_keyboard();
            }
            return false;
    }

    return true;
}
